"""SQLite storage. Three tables:

rides       one recorded drive (video + GPS track)
detections  one physical defect as seen in one ride (already de-duplicated across frames)
defects     one physical defect on the road, linking detections from many rides
"""
from __future__ import annotations

import json
import os
import sqlite3
import threading
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = Path(os.environ.get("ROADSCAN_DATA", ROOT / "data"))
DB_PATH = DATA_DIR / "roadscan.db"
MEDIA_DIR = DATA_DIR / "media"

SCHEMA = """
CREATE TABLE IF NOT EXISTS rides (
    id INTEGER PRIMARY KEY,
    name TEXT NOT NULL,
    recorded_at TEXT NOT NULL,
    video_path TEXT,
    duration_s REAL,
    distance_m REAL,
    status TEXT NOT NULL DEFAULT 'pending',   -- pending | processing | done | failed
    progress REAL NOT NULL DEFAULT 0,
    error TEXT,
    track_json TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS defects (
    id INTEGER PRIMARY KEY,
    cls TEXT NOT NULL,
    lat REAL NOT NULL,
    lon REAL NOT NULL,
    first_seen TEXT,
    last_seen TEXT,
    n_obs INTEGER NOT NULL DEFAULT 0,
    severity REAL,
    level TEXT,
    area_m2 REAL,
    length_m REAL,
    trend_per_month REAL,
    missed_passes INTEGER NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'active'     -- active | possibly_repaired
);
CREATE TABLE IF NOT EXISTS detections (
    id INTEGER PRIMARY KEY,
    ride_id INTEGER NOT NULL REFERENCES rides(id) ON DELETE CASCADE,
    defect_id INTEGER REFERENCES defects(id),
    t REAL NOT NULL,
    lat REAL NOT NULL,
    lon REAL NOT NULL,
    cls TEXT NOT NULL,
    conf REAL NOT NULL,
    severity REAL NOT NULL,
    level TEXT NOT NULL,
    area_m2 REAL,
    length_m REAL,
    n_frames INTEGER,
    crop_path TEXT
);
CREATE INDEX IF NOT EXISTS idx_det_ride ON detections(ride_id);
CREATE INDEX IF NOT EXISTS idx_det_defect ON detections(defect_id);
"""

# Columns added after the first release. connect() adds any that are missing so existing
# databases keep working.
MIGRATIONS = {
    "rides": {
        # synthetic: generated by scripts/seed_demo.py; model: detections from the trained detector.
        "source": "TEXT NOT NULL DEFAULT 'model'",
        # device: phone/dashcam GPS; reconstructed: rebuilt from a map + video landmarks;
        # simulated: generated (synthetic rides only).
        "gps_source": "TEXT NOT NULL DEFAULT 'device'",
        # Lighting check (roadscan/lighting.py): ok | low_light | too_dark | unknown; NULL = not checked.
        "lighting": "TEXT",
        "median_luma": "REAL",
        "dark_fraction": "REAL",
    },
    "defects": {
        "source": "TEXT NOT NULL DEFAULT 'model'",
        "first_severity": "REAL",
        "span_days": "REAL",
    },
}
SOURCES = ("model", "synthetic")
GPS_SOURCES = ("device", "reconstructed", "simulated")

_lock = threading.Lock()


def connect(path: Path | None = None) -> sqlite3.Connection:
    path = path or DB_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(path, check_same_thread=False, timeout=30)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    conn.execute("PRAGMA journal_mode = WAL")
    conn.executescript(SCHEMA)
    for table, cols in MIGRATIONS.items():
        have = {r[1] for r in conn.execute(f"PRAGMA table_info({table})")}
        for col, ddl in cols.items():
            if col not in have:
                conn.execute(f"ALTER TABLE {table} ADD COLUMN {col} {ddl}")
    conn.commit()
    return conn


def write_lock() -> threading.Lock:
    """Serialises writers (background processing threads + API) on one DB file."""
    return _lock


def rows(cur) -> list[dict]:
    return [dict(r) for r in cur.fetchall()]


def create_ride(conn, name: str, recorded_at: str, track_json: list, video_path: str | None,
                duration_s: float, distance_m: float, source: str = "model", gps_source: str = "device") -> int:
    if source not in SOURCES or gps_source not in GPS_SOURCES:
        raise ValueError(f"bad source/gps_source: {source}/{gps_source}")
    cur = conn.execute(
        """INSERT INTO rides (name, recorded_at, video_path, duration_s, distance_m, track_json, source, gps_source)
           VALUES (?,?,?,?,?,?,?,?)""",
        (name, recorded_at, video_path, duration_s, distance_m, json.dumps(track_json), source, gps_source),
    )
    conn.commit()
    return cur.lastrowid


def set_ride_status(conn, ride_id: int, status: str, progress: float | None = None, error: str | None = None):
    if progress is None:
        conn.execute("UPDATE rides SET status=?, error=? WHERE id=?", (status, error, ride_id))
    else:
        conn.execute("UPDATE rides SET status=?, progress=?, error=? WHERE id=?", (status, progress, error, ride_id))
    conn.commit()


def set_lighting(conn, ride_id: int, result: dict) -> None:
    conn.execute("UPDATE rides SET lighting=?, median_luma=?, dark_fraction=? WHERE id=?",
                 (result["lighting"], result["median_luma"], result["dark_fraction"], ride_id))
    conn.commit()
